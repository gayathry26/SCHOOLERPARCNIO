export function canAccessModule(role: UserRole, module: AppModule): boolean {
  const allowed = ROLE_MODULE_PERMISSIONS[role];
  return Boolean(allowed && allowed.includes(module));
}

export function hasPermission(
  user: SessionUser | null,
  module: AppModule,
  action: AppAction
): boolean {
  if (!user) return false;
  if (!canAccessModule(user.role, module)) return false;

  // Granular action rules
  if (action === 'VIEW') return true;

  if (action === 'APPROVE') {
    return ['SUPER_ADMIN', 'SCHOOL_ADMIN', 'PRINCIPAL', 'VICE_PRINCIPAL', 'HR_MANAGER'].includes(
      user.role
    );
  }

  if (action === 'DELETE') {
    return ['SUPER_ADMIN', 'SCHOOL_ADMIN', 'PRINCIPAL'].includes(user.role);
  }

  if (action === 'CREATE' || action === 'EDIT') {
    if (['STUDENT', 'PARENT'].includes(user.role)) {
      // Students and parents can only create specific items (e.g. submit mock test, pay fees, sign consent)
      return ['AI_LEARNING', 'PARENT_PORTAL', 'EVENTS'].includes(module);
    }
    return true;
  }

  return false;
}
